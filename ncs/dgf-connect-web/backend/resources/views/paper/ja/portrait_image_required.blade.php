## 必要な作業

モバイルアプリを開き、以下のガイドラインに従って高品質の顔写真をアップロードしてください：

- **顔がはっきり見える:** 顔がはっきりと見え、中央に配置されている
- **良好な照明:** 自然光または明るい照明を使用 - 顔に影が落ちないようにする
- **遮蔽物なし:** 帽子、サングラス、または顔を覆うものを外す
- **シンプルな背景:** 可能であれば、シンプルで雑然としていない背景を使用する
- **正面からのカメラアングル:** カメラに対して正面を向く、斜めからではない

## アップロード方法

1. DGF Connectモバイルアプリを開く
2. プロフィールセクションに移動
3. 顔写真をアップロード
4. 承認を待つ

有効な顔写真がアップロードされ承認されるまで、アカウントアクセスが制限される場合があります。

