# Cần hành động: Yêu cầu ảnh chân dung

Xin chào {{ $name ?? 'bạn' }},

Chúng tôi cần sự giúp đỡ của bạn để hoàn tất thiết lập hồ sơ. **Ảnh chân dung là bắt buộc** cho hệ thống nhận dạng khuôn mặt của chúng tôi.

## Bạn cần làm gì

Vui lòng mở ứng dụng di động và tải lên ảnh chân dung chất lượng cao theo các hướng dẫn sau:

- **Khuôn mặt rõ ràng:** Khuôn mặt của bạn phải được nhìn thấy rõ ràng và ở giữa
- **Ánh sáng tốt:** Sử dụng ánh sáng tự nhiên hoặc ánh sáng sáng - tránh bóng tối trên khuôn mặt
- **Không che khuất:** Tháo mũ, kính râm hoặc bất kỳ thứ gì che khuôn mặt
- **Nền đơn giản:** Sử dụng nền đơn giản, không lộn xộn nếu có thể
- **Góc máy ảnh trực tiếp:** Quay mặt trực diện vào máy ảnh, không chụp góc nghiêng

## Cách tải lên

1. Mở ứng dụng di động DGF Connect
2. Đi đến phần hồ sơ của bạn
3. Tải ảnh chân dung của bạn lên
4. Chờ phê duyệt

Quyền truy cập tài khoản của bạn có thể bị hạn chế cho đến khi ảnh chân dung hợp lệ được tải lên và phê duyệt.

Nếu bạn có bất kỳ câu hỏi nào hoặc cần hỗ trợ, vui lòng liên hệ với đội ngũ hỗ trợ của chúng tôi.

